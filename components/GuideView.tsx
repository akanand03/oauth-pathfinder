import { ActorTag, DifficultyBadge, EvidenceTag } from "./Badges";
import { CommunityNotes } from "./CommunityNotes";
import { AgentDrafts, ScopeAdvisor, Timeline } from "./GuideExtras";
import type { Guide, Requirement } from "@/lib/types";
import { formatUsd, type GuideUsage } from "@/lib/usage";

const STATUS_LABEL: Record<Requirement["status"], { text: string; cls: string }> = {
  required: { text: "Required", cls: "text-rose-700 dark:text-rose-400" },
  conditional: { text: "Sometimes", cls: "text-amber-700 dark:text-amber-400" },
  not_required: { text: "Not needed", cls: "text-emerald-700 dark:text-emerald-400" },
  unknown: { text: "Unknown", cls: "text-zinc-500" },
};

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <section className="space-y-3">
      <h2 className="text-lg font-semibold">{title}</h2>
      {children}
    </section>
  );
}

const card = "rounded-xl border border-zinc-200 bg-white p-5 dark:border-zinc-800 dark:bg-zinc-900";

export function GuideView({ guide }: { guide: Guide }) {
  const counts = countEvidence(guide);
  return (
    <article className="space-y-10">
      <header className={`${card} space-y-4`}>
        <div className="flex flex-wrap items-center gap-3">
          <h1 className="text-2xl font-bold">{guide.name}</h1>
          <DifficultyBadge difficulty={guide.verdict.difficulty} />
          <span className="text-xs text-zinc-500">
            {guide.kind === "generated" ? "Generated by research agent" : "Library guide"} · Last checked {guide.lastChecked}
          </span>
        </div>
        <p className="text-zinc-700 dark:text-zinc-300">{guide.verdict.summary}</p>
        <div className="grid gap-4 sm:grid-cols-2">
          <div>
            <div className="text-xs uppercase tracking-wide text-zinc-500">Time to first test</div>
            <div className="font-medium">{guide.verdict.timeToFirstTest.text}</div>
            <EvidenceTag evidence={guide.verdict.timeToFirstTest.evidence} />
          </div>
          <div>
            <div className="text-xs uppercase tracking-wide text-zinc-500">Time to production approval</div>
            <div className="font-medium">{guide.verdict.timeToProduction.text}</div>
            <EvidenceTag evidence={guide.verdict.timeToProduction.evidence} />
          </div>
        </div>
        <p className="text-xs text-zinc-500">
          Evidence: {counts.Tested} tested · {counts.Docs} from docs · {counts.Uncertain} uncertain
        </p>
        {guide.usage && <UsageSummary usage={guide.usage} />}
      </header>

      <Section title="Timeline">
        <Timeline guide={guide} />
      </Section>

      {guide.callouts.length > 0 && (
        <Section title="Know before you start">
          <ul className="space-y-2">
            {guide.callouts.map((c, i) => (
              <li key={i} className="rounded-lg border-l-4 border-indigo-400 bg-indigo-50/60 p-3 text-sm dark:bg-indigo-950/30">
                {c.text} <EvidenceTag evidence={c.evidence} />
              </li>
            ))}
          </ul>
        </Section>
      )}

      <Section title="Step-by-step path">
        <ol className="space-y-3">
          {guide.steps.map((s, i) => (
            <li key={i} className={`${card} flex gap-4 !p-4`}>
              <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-zinc-100 text-sm font-semibold dark:bg-zinc-800">
                {i + 1}
              </span>
              <div className="space-y-1">
                <div className="flex flex-wrap items-center gap-2">
                  <span className="font-medium">{s.title}</span>
                  <ActorTag actor={s.actor} />
                </div>
                <p className="text-sm text-zinc-600 dark:text-zinc-400">{s.detail}</p>
                <EvidenceTag evidence={s.evidence} />
              </div>
            </li>
          ))}
        </ol>
      </Section>

      <Section title="Requirements checklist">
        <div className={`${card} divide-y divide-zinc-100 !p-0 dark:divide-zinc-800`}>
          {guide.requirements.map((r, i) => (
            <div key={i} className="grid gap-1 p-4 sm:grid-cols-[180px_100px_1fr]">
              <span className="font-medium">{r.item}</span>
              <span className={`text-sm font-medium ${STATUS_LABEL[r.status].cls}`}>{STATUS_LABEL[r.status].text}</span>
              <span className="text-sm text-zinc-600 dark:text-zinc-400">
                {r.detail} <EvidenceTag evidence={r.evidence} />
              </span>
            </div>
          ))}
        </div>
      </Section>

      <Section title="Scope Advisor">
        <div className="grid gap-4 sm:grid-cols-2">
          <div className={card}>
            <h3 className="mb-3 text-sm font-semibold text-rose-700 dark:text-rose-400">Triggers review</h3>
            {guide.scopes.triggerReview.length === 0 && <p className="text-sm text-zinc-500">No scopes trigger review.</p>}
            <ul className="space-y-3">
              {guide.scopes.triggerReview.map((s, i) => (
                <li key={i} className="text-sm">
                  <code className="break-all font-mono text-xs">{s.scope}</code>
                  <p className="text-zinc-600 dark:text-zinc-400">{s.why}</p>
                  <EvidenceTag evidence={s.evidence} />
                </li>
              ))}
            </ul>
          </div>
          <div className={card}>
            <h3 className="mb-3 text-sm font-semibold text-emerald-700 dark:text-emerald-400">No review</h3>
            <ul className="space-y-3">
              {guide.scopes.noReview.map((s, i) => (
                <li key={i} className="text-sm">
                  <code className="break-all font-mono text-xs">{s.scope}</code>
                  <p className="text-zinc-600 dark:text-zinc-400">{s.why}</p>
                  <EvidenceTag evidence={s.evidence} />
                </li>
              ))}
            </ul>
          </div>
        </div>
        <ScopeAdvisor guide={guide} />
      </Section>

      <Section title="Blockers and how to handle them">
        <div className="space-y-3">
          {guide.blockers.map((b, i) => (
            <div key={i} className={`${card} !p-4`}>
              <div className="font-medium">{b.reason}</div>
              <p className="text-sm text-zinc-600 dark:text-zinc-400">→ {b.fix}</p>
              <EvidenceTag evidence={b.evidence} />
            </div>
          ))}
        </div>
      </Section>

      {guide.drafts && (
        <Section title="Agent drafts for you">
          <AgentDrafts drafts={guide.drafts} />
        </Section>
      )}

      {guide.kind === "library" && (
        <Section title="💬 What developers wish they knew">
          <CommunityNotes guide={guide} />
        </Section>
      )}

      <Section title="Composio shortcut">
        <div className={`${card} space-y-2`}>
          <div className="font-medium">
            {guide.composio.managed === "yes"
              ? `Managed OAuth app available${guide.composio.toolkit ? ` (${guide.composio.toolkit})` : ""}`
              : guide.composio.managed === "no"
                ? "No managed OAuth app: bring your own"
                : "Unknown"}
          </div>
          <p className="text-sm text-zinc-600 dark:text-zinc-400">{guide.composio.note}</p>
          <EvidenceTag evidence={guide.composio.evidence} />
        </div>
      </Section>

      {guide.portalObservation && (
        <Section title="What the agent saw on the developer portal">
          <div className={`${card} space-y-2 text-sm`}>
            {guide.portalObservation.url && (
              <a href={guide.portalObservation.url} target="_blank" rel="noopener noreferrer" className="break-all text-indigo-600 hover:underline dark:text-indigo-400">
                {guide.portalObservation.url}
              </a>
            )}
            {guide.portalObservation.fields.length > 0 ? (
              <ul className="list-inside list-disc">
                {guide.portalObservation.fields.map((f) => (
                  <li key={f}>{f}</li>
                ))}
              </ul>
            ) : (
              <p className="text-zinc-500">No form fields observed.</p>
            )}
            <p className="text-zinc-600 dark:text-zinc-400">{guide.portalObservation.note}</p>
          </div>
        </Section>
      )}

      <Section title="Sources">
        <ul className="space-y-1 text-sm">
          {guide.sources.map((s) => (
            <li key={s}>
              <a href={s} target="_blank" rel="noopener noreferrer" className="break-all text-indigo-600 hover:underline dark:text-indigo-400">
                {s}
              </a>
            </li>
          ))}
        </ul>
      </Section>
    </article>
  );
}

function UsageSummary({ usage }: { usage: GuideUsage }) {
  return (
    <details className="rounded-lg bg-zinc-50 p-3 text-xs text-zinc-600 dark:bg-zinc-950 dark:text-zinc-400">
      <summary className="cursor-pointer select-none">
        <span className="font-medium text-zinc-800 dark:text-zinc-200">{usage.totalTokens.toLocaleString()} tokens used</span>
        {" · "}estimated cost {formatUsd(usage.estimatedCostUsd)} · {usage.searches} searches ·{" "}
        {usage.pagesFetched} pages read{usage.pagesFromCache > 0 ? ` (${usage.pagesFromCache} from cache)` : ""}
      </summary>
      <table className="mt-2 w-full text-left tabular-nums">
        <thead>
          <tr className="text-zinc-500">
            <th className="font-normal">Stage</th>
            <th className="font-normal">Model</th>
            <th className="text-right font-normal">In</th>
            <th className="text-right font-normal">Out</th>
            <th className="text-right font-normal">Cost</th>
          </tr>
        </thead>
        <tbody>
          {usage.stages.map((s) => (
            <tr key={s.stage}>
              <td>{s.stage}</td>
              <td className="font-mono">{s.model.replace("openai/", "")}</td>
              <td className="text-right">{s.inputTokens.toLocaleString()}</td>
              <td className="text-right">{s.outputTokens.toLocaleString()}</td>
              <td className="text-right">{formatUsd(s.costUsd)}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="mt-2">Searches and page fetches use no model tokens. Viewing this guide again costs nothing; it&apos;s cached.</p>
    </details>
  );
}

function countEvidence(g: Guide) {
  const all = [
    g.verdict.timeToFirstTest.evidence,
    g.verdict.timeToProduction.evidence,
    ...g.callouts.map((c) => c.evidence),
    ...g.steps.map((s) => s.evidence),
    ...g.requirements.map((r) => r.evidence),
    ...g.scopes.triggerReview.map((s) => s.evidence),
    ...g.scopes.noReview.map((s) => s.evidence),
    ...g.blockers.map((b) => b.evidence),
    ...(g.scopeAdvisor ?? []).map((s) => s.evidence),
    ...(g.timeline ?? []).map((t) => t.evidence),
    g.composio.evidence,
  ];
  const counts = { Tested: 0, Docs: 0, Uncertain: 0 };
  for (const e of all) counts[e.label]++;
  return counts;
}
